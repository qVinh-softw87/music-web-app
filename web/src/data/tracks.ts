export function getTracksByIds(ids: number[]): Track[] {
  return ids.map((id) => tracks.find((t) => t.id === id)).filter(Boolean) as Track[];
}

export function getTracksByArtist(artistId: number): Track[] {
  return tracks.filter((t) => t.artistId === artistId);
}

export function getTracksByAlbum(albumId: number): Track[] {
  return tracks.filter((t) => t.albumId === albumId);
}

